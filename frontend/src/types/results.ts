/**
 * Results aggregation types for batch/swarm execution data.
 * These types align with backend Go structures in:
 * - repository.AgentExecution
 * - repository.UsageStats
 * - agent.SwarmResult
 * - agent.SwarmAgent
 */

/**
 * Status of a result/execution.
 * Maps to backend status strings used in AgentExecution and SwarmStatus.
 */
export type ResultStatus = 'pending' | 'running' | 'completed' | 'failed' | 'cancelled';

/**
 * Swarm execution strategies.
 * Maps to backend agent.SwarmStrategy constants.
 */
export type SwarmStrategy =
  | 'parallel'
  | 'pipeline'
  | 'debate'
  | 'consensus'
  | 'map_reduce'
  | 'specialist';

/**
 * Agent role specializations.
 * Maps to backend agent.AgentRole constants.
 */
export type AgentRole =
  | 'general'
  | 'planner'
  | 'coder'
  | 'reviewer'
  | 'researcher'
  | 'writer'
  | 'analyst'
  | 'debugger'
  | 'tester'
  | 'synthesizer';

/**
 * Token usage and cost metrics for an execution.
 * Maps to backend repository.UsageStats and AgentExecution cost fields.
 */
export interface ExecutionMetrics {
  /** Number of tokens used in the prompt/input */
  promptTokens: number;
  /** Number of tokens generated in completion/output */
  completionTokens: number;
  /** Total tokens (prompt + completion) */
  totalTokens: number;
  /** Cost of input tokens in the specified currency */
  inputCost: number;
  /** Cost of output tokens in the specified currency */
  outputCost: number;
  /** Total cost (input + output) */
  totalCost: number;
  /** Currency code (e.g., 'USD') */
  currency: string;
  /** Execution duration in milliseconds */
  durationMs?: number;
  /** Tokens generated per second */
  tokensPerSecond?: number;
}

/**
 * Tool call within an agent execution.
 * Maps to backend repository.AgentToolCall.
 */
export interface AgentToolCallDetail {
  /** Unique identifier for the tool call */
  id: string;
  /** ID of the parent execution */
  executionId: string;
  /** ID of the message that triggered this tool call */
  messageId?: string;
  /** Name of the tool that was called */
  toolName: string;
  /** Parameters passed to the tool */
  parameters: Record<string, unknown>;
  /** Output returned by the tool */
  output?: string;
  /** Error message if the tool call failed */
  error?: string;
  /** Current status of the tool call */
  status: 'pending' | 'running' | 'completed' | 'failed';
  /** Duration of the tool call in milliseconds */
  durationMs?: number;
  /** When the tool call was created */
  createdAt: Date;
  /** When the tool call completed */
  completedAt?: Date;
}

/**
 * Individual agent result within a swarm or batch execution.
 * Maps to backend agent.SwarmResult and repository.AgentExecution.
 */
export interface AgentResultDetail {
  /** Unique identifier for the agent */
  id: string;
  /** ID of the parent execution */
  executionId: string;
  /** User ID associated with this execution */
  userId?: string;
  /** Provider name (e.g., 'prism', 'anthropic') */
  provider: string;
  /** LLM provider used */
  llmProvider: string;
  /** Model identifier */
  model: string;
  /** Name of the agent */
  agentName: string;
  /** Role of the agent within a swarm */
  role?: AgentRole;
  /** Current status */
  status: ResultStatus;
  /** Input provided to the agent */
  input?: string;
  /** Output generated by the agent */
  output?: string;
  /** Error message if execution failed */
  error?: string;
  /** Whether the execution was successful */
  success: boolean;
  /** Execution metrics (tokens, costs, timing) */
  metrics: ExecutionMetrics;
  /** Tool calls made during execution */
  toolCalls?: AgentToolCallDetail[];
  /** Additional metadata */
  metadata?: Record<string, unknown>;
  /** When execution started */
  startedAt?: Date;
  /** When execution completed */
  completedAt?: Date;
  /** When the record was created */
  createdAt: Date;
}

/**
 * Summary of a swarm execution.
 * Maps to backend agent.Swarm structure.
 */
export interface SwarmResultSummary {
  /** Unique identifier for the swarm */
  id: string;
  /** Name of the swarm configuration */
  name: string;
  /** Execution strategy used */
  strategy: SwarmStrategy;
  /** Current status of the swarm */
  status: ResultStatus;
  /** Number of agents in the swarm */
  agentCount: number;
  /** Maximum number of agents allowed */
  maxAgents: number;
  /** Timeout duration in milliseconds */
  timeoutMs: number;
  /** Individual agent results */
  agentResults: AgentResultDetail[];
  /** Final synthesized output */
  finalOutput?: string;
  /** Error message if swarm execution failed */
  error?: string;
  /** Aggregated metrics across all agents */
  aggregatedMetrics: ExecutionMetrics;
  /** When the swarm was created */
  createdAt: Date;
  /** When execution started */
  startedAt?: Date;
  /** When execution completed */
  completedAt?: Date;
}

/**
 * Summary of a batch execution (multiple independent agent runs).
 */
export interface BatchResultSummary {
  /** Unique identifier for the batch */
  id: string;
  /** Name/description of the batch */
  name?: string;
  /** Current status of the batch */
  status: ResultStatus;
  /** Total number of executions in the batch */
  totalCount: number;
  /** Number of completed executions */
  completedCount: number;
  /** Number of failed executions */
  failedCount: number;
  /** Number of pending/running executions */
  pendingCount: number;
  /** Individual execution results */
  executions: AgentResultDetail[];
  /** Aggregated metrics across all executions */
  aggregatedMetrics: ExecutionMetrics;
  /** When the batch was created */
  createdAt: Date;
  /** When execution started */
  startedAt?: Date;
  /** When all executions completed */
  completedAt?: Date;
}

/**
 * Combined aggregated results supporting both swarm and batch data.
 * Primary type for results aggregation views.
 */
export interface AggregatedResults {
  /** Type of aggregation */
  type: 'swarm' | 'batch' | 'single';
  /** Swarm-specific data (if type is 'swarm') */
  swarm?: SwarmResultSummary;
  /** Batch-specific data (if type is 'batch') */
  batch?: BatchResultSummary;
  /** Single execution data (if type is 'single') */
  execution?: AgentResultDetail;
  /** Overall status */
  status: ResultStatus;
  /** Total aggregated metrics */
  totalMetrics: ExecutionMetrics;
  /** When the aggregation was created */
  createdAt: Date;
  /** When execution started */
  startedAt?: Date;
  /** When all executions completed */
  completedAt?: Date;
}

/**
 * Sort direction for result filtering.
 */
export type SortDirection = 'asc' | 'desc';

/**
 * Fields available for sorting results.
 */
export type ResultSortField =
  | 'createdAt'
  | 'startedAt'
  | 'completedAt'
  | 'status'
  | 'totalCost'
  | 'totalTokens'
  | 'durationMs';

/**
 * Filter options for querying and displaying results.
 */
export interface ResultFilter {
  /** Filter by status(es) */
  status?: ResultStatus[];
  /** Filter by provider(s) */
  providers?: string[];
  /** Filter by model(s) */
  models?: string[];
  /** Filter by agent role(s) */
  roles?: AgentRole[];
  /** Filter by swarm strategy */
  strategies?: SwarmStrategy[];
  /** Filter by date range start */
  dateFrom?: Date;
  /** Filter by date range end */
  dateTo?: Date;
  /** Filter by minimum cost */
  minCost?: number;
  /** Filter by maximum cost */
  maxCost?: number;
  /** Filter by minimum token count */
  minTokens?: number;
  /** Filter by maximum token count */
  maxTokens?: number;
  /** Text search query */
  searchQuery?: string;
  /** Field to sort by */
  sortBy?: ResultSortField;
  /** Sort direction */
  sortDirection?: SortDirection;
  /** Number of results to return */
  limit?: number;
  /** Offset for pagination */
  offset?: number;
}

/**
 * Swarm event types for real-time updates.
 * Maps to backend agent.SwarmEventType constants.
 */
export type SwarmEventType =
  | 'swarm_started'
  | 'agent_started'
  | 'agent_output'
  | 'agent_completed'
  | 'agent_failed'
  | 'message'
  | 'synthesizing'
  | 'swarm_completed'
  | 'swarm_failed'
  | 'swarm_cancelled'
  | 'progress';

/**
 * Real-time event from a swarm execution.
 * Maps to backend agent.SwarmEvent.
 */
export interface SwarmEvent {
  /** ID of the swarm emitting the event */
  swarmId: string;
  /** Type of event */
  type: SwarmEventType;
  /** ID of the agent (if applicable) */
  agentId?: string;
  /** Role of the agent (if applicable) */
  role?: AgentRole;
  /** Additional event data */
  data?: Record<string, unknown>;
  /** When the event occurred */
  timestamp: Date;
}

/**
 * Inter-agent message within a swarm.
 * Maps to backend agent.SwarmMessage.
 */
export interface SwarmMessage {
  /** Unique identifier for the message */
  id: string;
  /** ID of the sending agent */
  fromAgent: string;
  /** ID of the receiving agent (empty for broadcast) */
  toAgent?: string;
  /** Type of message */
  type: 'output' | 'request' | 'feedback' | 'critique';
  /** Message content */
  content: string;
  /** When the message was sent */
  timestamp: Date;
}

/**
 * Usage statistics aggregated over a time period.
 * Maps to backend repository.UsageStats.
 */
export interface UsageStats {
  /** Total number of executions */
  totalExecutions: number;
  /** Total prompt tokens used */
  totalPromptTokens: number;
  /** Total completion tokens generated */
  totalCompletionTokens: number;
  /** Total tokens (prompt + completion) */
  totalTokens: number;
  /** Total cost incurred */
  totalCost: number;
  /** Currency for cost values */
  currency: string;
  /** Start of the aggregation period */
  periodStart?: Date;
  /** End of the aggregation period */
  periodEnd?: Date;
}
